# Upstream skill catalog snapshot: folder names and pinned paths recorded from the real
# vendor clones. It holds identifiers only - no upstream skill text is copied.
function Get-SkillCatalogSnapshot {
    return ([IO.File]::ReadAllText((Join-Path $PSScriptRoot 'fixtures\skill-catalog.snapshot.json')) | ConvertFrom-Json)
}

# Builds a stand-in vendor catalog under $Root from the snapshot (one SKILL.md per skill).
function New-SkillCatalogFixture {
    param([string]$Root, $Snapshot = (Get-SkillCatalogSnapshot))
    # Synthetic descriptions (not upstream text) carrying the words behind earlier keyword mismatches.
    $descriptions = @{
        'project-osmos'                      = 'Run Project Osmos tasks that build medallion layers on OneLake.'
        'hdinsight-migration'                = 'Port HDInsight workloads to Delta tables in a Lakehouse with OneLake shortcuts.'
        'onelake-catalog-cli'                = 'OneLake catalog governance audits and owner curation of item metadata.'
        'git-integration-operations-cli'     = 'Fabric Git integration: connect, commit and update workspaces.'
        'deployment-pipelines-authoring-cli' = 'Fabric deployment pipelines for stage promotion.'
        'pbir-cli'                           = 'Edit PBIR reports in pbip or pbix files with the pbir CLI.'
        'svg-visuals'                        = 'SVG images generated by DAX measures.'
        'fabric-capacity'                    = 'Fabric capacity utilisation, throttling and start or pause.'
        'powerbi-custom-visuals'             = 'Power BI custom visual (pbiviz) development.'
        'deneb-visuals'                      = 'Deneb and Vega-Lite visuals in PBIR reports.'
        'organize-semantic-model'            = 'Organize a semantic model: names, folders, descriptions and roles.'
        'refresh-semantic-model'             = 'Refresh a semantic model and manage its schedule.'
        'semantic-model'                     = 'Design, build and review a semantic model.'
    }
    $utf8 = New-Object System.Text.UTF8Encoding($false)
    foreach ($rel in @($Snapshot.skills)) {
        $dir = Join-Path $Root ($rel -replace '/', '\')
        New-Item -ItemType Directory -Path $dir -Force | Out-Null
        $leaf = ($rel -split '/')[-1]
        $desc = if ($descriptions.ContainsKey($leaf)) { $descriptions[$leaf] } else { "Fixture skill $leaf." }
        [IO.File]::WriteAllText((Join-Path $dir 'SKILL.md'), "---`nname: $leaf`ndescription: $desc`n---`n`n# $leaf (fixture)`n", $utf8)
    }
    foreach ($e in @($Snapshot.paths)) {
        $full = Join-Path $Root ($e.path -replace '/', '\')
        if ($e.type -eq 'dir') { New-Item -ItemType Directory -Path $full -Force | Out-Null; continue }
        New-Item -ItemType Directory -Path (Split-Path $full -Parent) -Force | Out-Null
        if (-not (Test-Path -LiteralPath $full)) { [IO.File]::WriteAllText($full, "fixture`n", $utf8) }
    }
}

# Identity, permission and knowledge facts of one generated .agent.md file.
function Get-GeneratedAgentRecord {
    param([string]$Path)
    $text = [IO.File]::ReadAllText($Path) -replace "`r`n", "`n"
    $lines = $text -split "`n"
    $fm = @{}
    for ($i = 1; $i -lt $lines.Count -and $lines[$i] -ne '---'; $i++) {
        if ($lines[$i] -match '^([a-z-]+):\s*(.*)$') { $fm[$Matches[1]] = $Matches[2] }
    }
    $listOf = { param($v) @([regex]::Matches([string]$v, "'((?:[^']|'')*)'") | ForEach-Object { $_.Groups[1].Value.Replace("''", "'") }) }
    $section = {
        param([string]$StartPattern)
        $out = @(); $on = $false
        foreach ($l in $lines) {
            if ($on) { if ($l -notlike '- *') { break }; $out += $l }
            elseif ($l -match $StartPattern) { $on = $true }
        }
        $out
    }
    $auto = @(& $section '^(Also relevant|Related upstream skills)' | ForEach-Object { [regex]::Match($_, '^- `([^`]+)`').Groups[1].Value })
    $tailAt = $text.IndexOf("`n## Playbook")
    $tail = if ($tailAt -ge 0) { $text.Substring($tailAt) } else { '' }
    $sha = [System.Security.Cryptography.SHA256]::Create()
    try { $tailSha = ([BitConverter]::ToString($sha.ComputeHash([Text.Encoding]::UTF8.GetBytes($tail)))).Replace('-', '') } finally { $sha.Dispose() }
    $wp = [regex]::Match($text, '(?m)^Write permission: (.*)$').Groups[1].Value
    return [pscustomobject][ordered]@{
        file            = Split-Path $Path -Leaf
        name            = ([string]$fm['name']).Trim("'").Replace("''", "'")
        description     = ([string]$fm['description']).Trim("'").Replace("''", "'")
        userInvocable   = [string]$fm['user-invocable']
        tools           = @(& $listOf $fm['tools'])
        agents          = @(& $listOf $fm['agents'])
        writePermission = $wp
        pinned          = @(& $section '^Read these before acting')
        auto            = $auto
        tailSha256      = $tailSha
    }
}
